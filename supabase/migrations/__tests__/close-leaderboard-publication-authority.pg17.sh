SQL

# Both rolling-deploy authority paths are genuinely open before postdeploy.
expect_value \
  "legacy direct freshness update" \
  "1" \
  service_role \
  "WITH changed AS (UPDATE public.leaderboard_source_freshness SET source_as_of = '2026-07-29 11:00:00+00' WHERE season_id = '7D' RETURNING 1) SELECT pg_catalog.count(*) FROM changed;"
expect_value \
  "standalone seal before cutover" \
  "sealed" \
  service_role \
  "SELECT public.seal_leaderboard_rank_publication('7D', '10000000-0000-4000-8000-000000000001', '[]'::jsonb)->>'status';"

# Re-application must retain the exact closed authority boundary.
psql_cmd -q -f "$MIGRATION"
psql_cmd -q -f "$MIGRATION"

psql_cmd -q <<'SQL'
DO $catalog_assertions$
DECLARE
  v_role name;
  v_privilege text;
BEGIN
  FOREACH v_role IN ARRAY ARRAY[
    'service_role'::name,
    'anon'::name,
    'authenticated'::name
  ]
  LOOP
    IF NOT pg_catalog.has_table_privilege(
         v_role, 'public.leaderboard_source_freshness', 'SELECT'
       ) THEN
      RAISE EXCEPTION '% lost freshness SELECT', v_role;
    END IF;
    FOREACH v_privilege IN ARRAY ARRAY[
      'INSERT', 'UPDATE', 'DELETE', 'TRUNCATE',
      'REFERENCES', 'TRIGGER', 'MAINTAIN'
    ]::text[]
    LOOP
      IF pg_catalog.has_table_privilege(
           v_role, 'public.leaderboard_source_freshness', v_privilege
         ) THEN
        RAISE EXCEPTION '% retains freshness %', v_role, v_privilege;
      END IF;
    END LOOP;
  END LOOP;

  IF pg_catalog.has_function_privilege(
       'service_role',
       'public.seal_leaderboard_rank_publication(text,uuid,jsonb)',
       'EXECUTE'
     )
     OR NOT pg_catalog.has_function_privilege(
       'service_role',
       'public.finalize_leaderboard_rank_generation_v1(text,bigint,uuid,uuid,text,jsonb)',
       'EXECUTE'
     )
     OR NOT pg_catalog.has_function_privilege(
       'service_role',
       'public.arena_leaderboard_publication_proofs(text,text[])',
       'EXECUTE'
     ) THEN
    RAISE EXCEPTION 'publication function boundary drifted';
  END IF;
END
$catalog_assertions$;
SQL

# Public/API reads stay open.
expect_value \
  "service freshness read" \
  "1" \
  service_role \
  "SELECT pg_catalog.count(*) FROM public.leaderboard_source_freshness;"
expect_value \
  "anonymous freshness read" \
  "1" \
  anon \
  "SELECT pg_catalog.count(*) FROM public.leaderboard_source_freshness;"
expect_value \
  "authenticated freshness read" \
  "1" \
  authenticated \
  "SELECT pg_catalog.count(*) FROM public.leaderboard_source_freshness;"

# Direct freshness and private publication table access are closed.
for role in service_role anon authenticated; do
  expect_table_denied \
    "$role freshness insert" \
    "$role" \
    "INSERT INTO public.leaderboard_source_freshness (season_id, source, source_as_of) VALUES ('7D', '$role', pg_catalog.clock_timestamp());"
  expect_table_denied \
    "$role freshness update" \
    "$role" \
    "UPDATE public.leaderboard_source_freshness SET source_as_of = pg_catalog.clock_timestamp() WHERE season_id = '7D';"
  expect_table_denied \
    "$role freshness delete" \
    "$role" \
    "DELETE FROM public.leaderboard_source_freshness WHERE season_id = '7D';"
done
expect_table_denied \
  "private publication receipt read" \
  service_role \
  "SELECT * FROM arena.leaderboard_rank_publications;"
expect_table_denied \
  "private mutation fence write" \
  authenticated \
  "INSERT INTO arena.leaderboard_rank_mutation_fences VALUES ('7D', 'bad', 1);"

# Standalone sealing is closed for every application role.
for role in service_role anon authenticated; do
  expect_function_denied \
    "$role standalone seal" \
    "$role" \
    "SELECT public.seal_leaderboard_rank_publication('7D', '30000000-0000-4000-8000-000000000001', '[]'::jsonb);"
done
expect_function_denied \
  "anonymous proof reader" \
  anon \
  "SELECT * FROM public.arena_leaderboard_publication_proofs('7D', ARRAY['fixture']);"

# The service-only proof reader remains callable, and the canonical finalizer
# can still invoke the owner-only seal and write all private/public state.
expect_value \
  "canonical finalizer owns seal" \
  "finalized" \
  service_role \
  "SELECT public.finalize_leaderboard_rank_generation_v1('7D', 2, '20000000-0000-4000-8000-000000000001', '40000000-0000-4000-8000-000000000001', repeat('a', 64), '[]'::jsonb)->>'status';"
expect_value \
  "service proof reader" \
  "true|20000000-0000-4000-8000-000000000001" \
  service_role \
  "SELECT is_sealed || '|' || score_cohort_id FROM public.arena_leaderboard_publication_proofs('7D', ARRAY['fixture']);"
expect_value \
  "canonical publication state" \
  "1|2|20000000-0000-4000-8000-000000000001" \
  service_role \
  "SELECT pg_catalog.count(*) FILTER (WHERE source = 'fixture') || '|' || pg_catalog.max(marker) FILTER (WHERE source = 'fixture') || '|' || (SELECT freshness.score_cohort_id FROM public.leaderboard_source_freshness AS freshness WHERE freshness.season_id = '7D' AND freshness.source = 'fixture') FROM public.leaderboard_ranks;"

expect_table_denied \
  "service freshness remains read-only after finalizer" \
  service_role \
  "UPDATE public.leaderboard_source_freshness SET source_as_of = pg_catalog.clock_timestamp() WHERE season_id = '7D';"

echo "close leaderboard publication authority PostgreSQL 17 proof passed"
