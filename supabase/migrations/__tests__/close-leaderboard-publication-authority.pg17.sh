#!/usr/bin/env bash

# PostgreSQL 17 proof for the publication-authority cutover: application roles
# keep freshness/proof reads, but only the canonical finalizer can invoke the
# owner-only seal and mutate freshness or private publication receipts.

set -Eeuo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)"
MIGRATION="$ROOT_DIR/supabase/migrations/20260729154000_close_leaderboard_publication_authority.sql"
PG_BIN="${PG17_BIN:-/opt/homebrew/opt/postgresql@17/bin}"

for executable in initdb pg_ctl psql; do
  if [[ ! -x "$PG_BIN/$executable" ]]; then
    echo "PostgreSQL 17 executable not found: $PG_BIN/$executable" >&2
    exit 1
  fi
done
if [[ "$("$PG_BIN/psql" --version)" != psql\ \(PostgreSQL\)\ 17.* ]]; then
  echo "This integration proof requires PostgreSQL 17" >&2
  exit 1
fi

TMP_ROOT="$(mktemp -d /tmp/close-leaderboard-publication-pg17.XXXXXX)"
DATA_DIR="$TMP_ROOT/data"
SOCKET_DIR="$TMP_ROOT/socket"
LOG_FILE="$TMP_ROOT/postgres.log"
ERROR_FILE="$TMP_ROOT/expected-error.log"
PORT="${PGPORT_OVERRIDE:-$((49000 + ($$ % 9000)))}"
mkdir -p "$SOCKET_DIR"

cleanup() {
  local exit_code=$?
  if [[ -s "$DATA_DIR/postmaster.pid" ]]; then
    "$PG_BIN/pg_ctl" -D "$DATA_DIR" -m immediate -w stop >/dev/null 2>&1 || true
  fi
  if ((exit_code != 0)); then
    [[ -f "$ERROR_FILE" ]] && sed -n '1,180p' "$ERROR_FILE" >&2 || true
    [[ -f "$LOG_FILE" ]] && tail -240 "$LOG_FILE" >&2 || true
  fi
  rm -rf "$TMP_ROOT"
  exit "$exit_code"
}
trap cleanup EXIT

psql_cmd() {
  "$PG_BIN/psql" -X -v ON_ERROR_STOP=1 -v VERBOSITY=verbose \
    -h "$SOCKET_DIR" -p "$PORT" -U postgres -d postgres "$@"
}

role_query() {
  local role="$1"
  local sql="$2"
  psql_cmd -qAtc "
    SET ROLE $role;
    $sql
    RESET ROLE;
  "
}

expect_value() {
  local label="$1"
  local expected="$2"
  local role="$3"
  local sql="$4"
  local actual
  actual="$(role_query "$role" "$sql")"
  if [[ "$actual" != "$expected" ]]; then
    echo "$label drifted: expected '$expected', got '$actual'" >&2
    exit 1
  fi
}

expect_function_denied() {
  local label="$1"
  local role="$2"
  local sql="$3"
  if role_query "$role" "$sql" >"$ERROR_FILE" 2>&1; then
    echo "$label unexpectedly succeeded" >&2
    exit 1
  fi
  if ! grep -Eq 'permission denied for function|42501' "$ERROR_FILE"; then
    echo "$label failed for an unexpected reason" >&2
    sed -n '1,180p' "$ERROR_FILE" >&2
    exit 1
  fi
}

expect_table_denied() {
  local label="$1"
  local role="$2"
  local sql="$3"
  if role_query "$role" "$sql" >"$ERROR_FILE" 2>&1; then
    echo "$label unexpectedly succeeded" >&2
    exit 1
  fi
  if ! grep -Eq 'permission denied for table|42501' "$ERROR_FILE"; then
    echo "$label failed for an unexpected reason" >&2
    sed -n '1,180p' "$ERROR_FILE" >&2
    exit 1
  fi
}

"$PG_BIN/initdb" \
  -D "$DATA_DIR" \
  --auth-local=trust \
  --auth-host=trust \
  --encoding=UTF8 \
  --username=postgres \
  --no-locale >/dev/null
"$PG_BIN/pg_ctl" \
  -D "$DATA_DIR" \
  -l "$LOG_FILE" \
  -o "-F -p $PORT -k $SOCKET_DIR -c listen_addresses=" \
  -w start >/dev/null

psql_cmd -q <<'SQL'
CREATE ROLE anon NOLOGIN;
CREATE ROLE authenticated NOLOGIN;
CREATE ROLE service_role NOLOGIN BYPASSRLS;
CREATE ROLE delegated_publication_writer NOLOGIN;
GRANT delegated_publication_writer TO service_role;

CREATE SCHEMA arena AUTHORIZATION postgres;
GRANT USAGE ON SCHEMA public, arena
  TO anon, authenticated, service_role, delegated_publication_writer;

CREATE TABLE public.leaderboard_ranks (
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  season_id text NOT NULL,
  source text NOT NULL,
  source_trader_id text NOT NULL,
  marker integer NOT NULL DEFAULT 0,
  PRIMARY KEY (season_id, id),
  UNIQUE (season_id, source, source_trader_id)
) PARTITION BY LIST (season_id);
CREATE TABLE public.leaderboard_ranks_7d
  PARTITION OF public.leaderboard_ranks FOR VALUES IN ('7D');
ALTER TABLE public.leaderboard_ranks OWNER TO postgres;
GRANT SELECT ON TABLE public.leaderboard_ranks
  TO anon, authenticated, service_role;

CREATE TABLE public.leaderboard_source_freshness (
  season_id text NOT NULL,
  source text NOT NULL,
  source_as_of timestamptz NOT NULL,
  recorded_at timestamptz NOT NULL DEFAULT pg_catalog.statement_timestamp(),
  score_cohort_id uuid,
  rank_mutation_seq bigint,
  published_rank_count integer,
  published_identity_sha256 text,
  PRIMARY KEY (season_id, source)
);
ALTER TABLE public.leaderboard_source_freshness OWNER TO postgres;
ALTER TABLE public.leaderboard_source_freshness ENABLE ROW LEVEL SECURITY;
CREATE POLICY leaderboard_source_freshness_public_read
  ON public.leaderboard_source_freshness
  FOR SELECT
  USING (true);

CREATE TABLE arena.leaderboard_rank_mutation_fences (
  season_id text NOT NULL,
  source text NOT NULL,
  mutation_seq bigint NOT NULL,
  PRIMARY KEY (season_id, source)
);
CREATE TABLE arena.leaderboard_rank_publications (
  id uuid PRIMARY KEY,
  season_id text NOT NULL,
  published_at timestamptz NOT NULL DEFAULT pg_catalog.statement_timestamp()
);
CREATE TABLE arena.leaderboard_rank_cleanup_receipts (
  id uuid PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT pg_catalog.statement_timestamp()
);
ALTER TABLE arena.leaderboard_rank_mutation_fences OWNER TO postgres;
ALTER TABLE arena.leaderboard_rank_publications OWNER TO postgres;
ALTER TABLE arena.leaderboard_rank_cleanup_receipts OWNER TO postgres;

-- Already-retired finalizer helpers establish the required prior cutover.
CREATE FUNCTION public.cleanup_leaderboard_rank_publication(
  p_season_id text,
  p_score_cohort_id uuid,
  p_source_publications jsonb
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, pg_temp
AS $function$
BEGIN
  RETURN pg_catalog.jsonb_build_object('status', 'cleaned');
END;
$function$;
CREATE FUNCTION public.rerank_leaderboard_publication(
  p_season_id text,
  p_score_cohort_id uuid
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, pg_temp
AS $function$
BEGIN
  RETURN pg_catalog.jsonb_build_object('status', 'reranked');
END;
$function$;
ALTER FUNCTION public.cleanup_leaderboard_rank_publication(text, uuid, jsonb)
  OWNER TO postgres;
ALTER FUNCTION public.rerank_leaderboard_publication(text, uuid)
  OWNER TO postgres;
REVOKE ALL ON FUNCTION public.cleanup_leaderboard_rank_publication(
  text, uuid, jsonb
) FROM PUBLIC, anon, authenticated, service_role;
REVOKE ALL ON FUNCTION public.rerank_leaderboard_publication(text, uuid)
  FROM PUBLIC, anon, authenticated, service_role;

CREATE FUNCTION public.seal_leaderboard_rank_publication(
  p_season_id text,
  p_score_cohort_id uuid,
  p_source_publications jsonb
)
RETURNS jsonb
LANGUAGE plpgsql
VOLATILE
SECURITY DEFINER
SET search_path = pg_catalog, pg_temp
SET lock_timeout = '10s'
AS $function$
DECLARE
  v_count integer;
BEGIN
  INSERT INTO arena.leaderboard_rank_publications (id, season_id)
  VALUES (p_score_cohort_id, p_season_id)
  ON CONFLICT (id) DO NOTHING;

  INSERT INTO arena.leaderboard_rank_mutation_fences (
    season_id,
    source,
    mutation_seq
  ) VALUES (
    p_season_id,
    'fixture',
    1
  )
  ON CONFLICT (season_id, source) DO UPDATE
  SET mutation_seq = arena.leaderboard_rank_mutation_fences.mutation_seq + 1
  RETURNING mutation_seq INTO STRICT v_count;

  INSERT INTO public.leaderboard_source_freshness (
    season_id,
    source,
    source_as_of,
    score_cohort_id,
    rank_mutation_seq,
    published_rank_count,
    published_identity_sha256
  ) VALUES (
    p_season_id,
    'fixture',
    '2026-07-29 12:00:00+00',
    p_score_cohort_id,
    v_count,
    1,
    repeat('a', 64)
  )
  ON CONFLICT (season_id, source) DO UPDATE
  SET
    source_as_of = EXCLUDED.source_as_of,
    recorded_at = pg_catalog.statement_timestamp(),
    score_cohort_id = EXCLUDED.score_cohort_id,
    rank_mutation_seq = EXCLUDED.rank_mutation_seq,
    published_rank_count = EXCLUDED.published_rank_count,
    published_identity_sha256 = EXCLUDED.published_identity_sha256;

  RETURN pg_catalog.jsonb_build_object('status', 'sealed');
END;
$function$;

CREATE FUNCTION public.finalize_leaderboard_rank_generation_v1(
  p_season_id text,
  p_generation_seq bigint,
  p_score_cohort_id uuid,
  p_score_input_manifest_id uuid,
  p_score_input_manifest_digest text,
  p_source_publications jsonb
)
RETURNS jsonb
LANGUAGE plpgsql
VOLATILE
SECURITY DEFINER
SET search_path = pg_catalog, pg_temp
SET "TimeZone" = 'UTC'
SET lock_timeout = '10s'
AS $function$
BEGIN
  INSERT INTO public.leaderboard_ranks (
    season_id,
    source,
    source_trader_id,
    marker
  ) VALUES (
    p_season_id,
    'fixture',
    p_score_cohort_id::text,
    p_generation_seq::integer
  )
  ON CONFLICT (season_id, source, source_trader_id) DO UPDATE
  SET marker = EXCLUDED.marker;

  PERFORM public.seal_leaderboard_rank_publication(
    p_season_id,
    p_score_cohort_id,
    p_source_publications
  );
  RETURN pg_catalog.jsonb_build_object('status', 'finalized');
END;
$function$;

CREATE FUNCTION public.arena_leaderboard_publication_proofs(
  p_season_id text,
  p_sources text[]
)
RETURNS TABLE (
  season_id text,
  source text,
  source_as_of timestamptz,
  recorded_at timestamptz,
  score_cohort_id uuid,
  rank_mutation_seq bigint,
  current_mutation_seq bigint,
  published_rank_count integer,
  published_identity_sha256 text,
  is_sealed boolean
)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, pg_temp
AS $function$
BEGIN
  RETURN QUERY
  SELECT
    freshness.season_id,
    freshness.source,
    freshness.source_as_of,
    freshness.recorded_at,
    freshness.score_cohort_id,
    freshness.rank_mutation_seq,
    fence.mutation_seq,
    freshness.published_rank_count,
    freshness.published_identity_sha256,
    freshness.rank_mutation_seq IS NOT DISTINCT FROM fence.mutation_seq
  FROM public.leaderboard_source_freshness AS freshness
  LEFT JOIN arena.leaderboard_rank_mutation_fences AS fence
    ON fence.season_id = freshness.season_id
   AND fence.source = freshness.source
  WHERE freshness.season_id = p_season_id
    AND freshness.source = ANY(p_sources)
  ORDER BY freshness.source;
END;
$function$;

ALTER FUNCTION public.seal_leaderboard_rank_publication(text, uuid, jsonb)
  OWNER TO postgres;
ALTER FUNCTION public.finalize_leaderboard_rank_generation_v1(
  text, bigint, uuid, uuid, text, jsonb
) OWNER TO postgres;
ALTER FUNCTION public.arena_leaderboard_publication_proofs(text, text[])
  OWNER TO postgres;

REVOKE ALL ON FUNCTION public.seal_leaderboard_rank_publication(
  text, uuid, jsonb
) FROM PUBLIC, anon, authenticated, service_role, delegated_publication_writer;
REVOKE ALL ON FUNCTION public.finalize_leaderboard_rank_generation_v1(
  text, bigint, uuid, uuid, text, jsonb
) FROM PUBLIC, anon, authenticated, service_role, delegated_publication_writer;
REVOKE ALL ON FUNCTION public.arena_leaderboard_publication_proofs(text, text[])
  FROM PUBLIC, anon, authenticated, service_role, delegated_publication_writer;
GRANT EXECUTE ON FUNCTION public.seal_leaderboard_rank_publication(
  text, uuid, jsonb
) TO service_role;
GRANT EXECUTE ON FUNCTION public.seal_leaderboard_rank_publication(
  text, uuid, jsonb
) TO delegated_publication_writer WITH GRANT OPTION;
GRANT EXECUTE ON FUNCTION public.finalize_leaderboard_rank_generation_v1(
  text, bigint, uuid, uuid, text, jsonb
) TO service_role;
GRANT EXECUTE ON FUNCTION public.arena_leaderboard_publication_proofs(
  text, text[]
) TO service_role;

-- Reproduce rolling-deploy table and column grants plus private table drift.
GRANT SELECT ON TABLE public.leaderboard_source_freshness
  TO anon, authenticated, service_role;
GRANT ALL PRIVILEGES ON TABLE public.leaderboard_source_freshness
  TO service_role;
GRANT INSERT, UPDATE, DELETE, TRUNCATE, REFERENCES, TRIGGER, MAINTAIN
  ON TABLE public.leaderboard_source_freshness
  TO PUBLIC, anon, authenticated;
GRANT INSERT (source), UPDATE (source_as_of), REFERENCES (season_id)
  ON TABLE public.leaderboard_source_freshness
  TO PUBLIC, anon, authenticated, service_role;
GRANT ALL PRIVILEGES
  ON TABLE
    arena.leaderboard_rank_mutation_fences,
    arena.leaderboard_rank_publications,
    arena.leaderboard_rank_cleanup_receipts
  TO service_role, authenticated;

INSERT INTO public.leaderboard_source_freshness (
