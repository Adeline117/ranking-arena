DO $sealed_before_shrink$
BEGIN
  IF NOT (
    SELECT pg_catalog.bool_and(proof.is_sealed)
    FROM public.arena_leaderboard_publication_proofs(
      '90D',
      ARRAY['beta', 'alpha']
    ) AS proof
  ) THEN
    RAISE EXCEPTION 'complete pre-shrink receipt was not sealed';
  END IF;
END
$sealed_before_shrink$;

UPDATE arena.sources
SET is_serving = false
WHERE season_id = '90D' AND filter_source = 'beta';

DO $unsealed_after_shrink$
DECLARE
  v_row_count integer;
  v_any_sealed boolean;
BEGIN
  SELECT pg_catalog.count(*), pg_catalog.bool_or(proof.is_sealed)
  INTO STRICT v_row_count, v_any_sealed
  FROM public.arena_leaderboard_publication_proofs(
    '90D',
    ARRAY['alpha']
  ) AS proof;

  IF v_row_count <> 1 OR v_any_sealed THEN
    RAISE EXCEPTION 'receipt with retired extra source remained sealed';
  END IF;
END
$unsealed_after_shrink$;
SQL

# Freeze the proof statement before a concurrent registry commit. The running
# call must return the complete old authority. A later call must see the
# complete new authority; neither call may mix them.
psql_cmd -qAt <<'SQL' >"$RACE_RESULT" &
BEGIN;
SET LOCAL fixture.pause_authority = 'on';
COPY (
  SELECT
    pg_catalog.string_agg(proof.source, ',' ORDER BY proof.source)
      || ':' || pg_catalog.count(*)::text
  FROM public.arena_leaderboard_publication_proofs(
    '30D',
    ARRAY['race_alpha', 'race_beta']
  ) AS proof
) TO STDOUT;
COMMIT;
SQL
RACE_PID=$!

for _ in $(seq 1 100); do
  if psql_cmd -qAt -c \
    "SELECT EXISTS (SELECT 1 FROM pg_catalog.pg_stat_activity WHERE pid <> pg_catalog.pg_backend_pid() AND wait_event = 'PgSleep' AND query LIKE '%race_alpha%')" \
    | rg -q '^t$'; then
    break
  fi
  sleep 0.05
done

if ! psql_cmd -qAt -c \
  "SELECT EXISTS (SELECT 1 FROM pg_catalog.pg_stat_activity WHERE pid <> pg_catalog.pg_backend_pid() AND wait_event = 'PgSleep' AND query LIKE '%race_alpha%')" \
  | rg -q '^t$'; then
  echo "proof race did not reach the authority pause" >&2
  kill "$RACE_PID" >/dev/null 2>&1 || true
  wait "$RACE_PID" || true
  exit 1
fi

psql_cmd -q -c \
  "INSERT INTO arena.sources (registry_slug, filter_source, season_id) VALUES ('race_gamma','race_gamma','30D')"
wait "$RACE_PID"

if [[ "$(tr -d '\r\n' <"$RACE_RESULT")" != "race_alpha,race_beta:2" ]]; then
  echo "concurrent proof returned a mixed authority set" >&2
  sed -n '1,80p' "$RACE_RESULT" >&2
  exit 1
fi

psql_cmd -qAt -c \
  "SELECT pg_catalog.string_agg(source, ',' ORDER BY source) || ':' || pg_catalog.count(*)::text FROM public.arena_leaderboard_publication_proofs('30D', ARRAY['race_gamma','race_beta','race_alpha'])" \
  | rg -q '^race_alpha,race_beta,race_gamma:3$'

expect_failure \
  "stale pre-race authority request" \
  "exactly match the season authority" \
  "SELECT * FROM public.arena_leaderboard_publication_proofs('30D', ARRAY['race_alpha','race_beta'])"

echo "leaderboard publication proof authority PG17 proof passed"
