#!/usr/bin/env bash

# PostgreSQL 17 behavioral proof for complete-authority publication reads,
# closed RPC ACLs, and one-snapshot registry races.

set -Eeuo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)"
MIGRATION="$ROOT_DIR/supabase/migrations/20260725014000_strengthen_leaderboard_publication_proof_authority.sql"
PG_BIN="${PG17_BIN:-/opt/homebrew/opt/postgresql@17/bin}"

for executable in initdb pg_ctl psql; do
  if [[ ! -x "$PG_BIN/$executable" ]]; then
    echo "PostgreSQL 17 executable not found: $PG_BIN/$executable" >&2
    exit 1
  fi
done
if [[ "$("$PG_BIN/psql" --version)" != psql\ \(PostgreSQL\)\ 17.* ]]; then
  echo "This integration proof requires PostgreSQL 17" >&2
  exit 1
fi

TMP_ROOT="$(mktemp -d /tmp/proof-authority-pg17.XXXXXX)"
DATA_DIR="$TMP_ROOT/data"
SOCKET_DIR="$TMP_ROOT/socket"
LOG_FILE="$TMP_ROOT/postgres.log"
ERROR_FILE="$TMP_ROOT/expected-error.log"
RACE_RESULT="$TMP_ROOT/race-result.txt"
PORT="${PGPORT_OVERRIDE:-$((59000 + ($$ % 5000)))}"
mkdir -p "$SOCKET_DIR"

cleanup() {
  local exit_code=$?
  if [[ -s "$DATA_DIR/postmaster.pid" ]]; then
    "$PG_BIN/pg_ctl" -D "$DATA_DIR" -m immediate -w stop >/dev/null 2>&1 || true
  fi
  if ((exit_code != 0)) && [[ -f "$LOG_FILE" ]]; then
    tail -200 "$LOG_FILE" >&2 || true
  fi
  rm -rf "$TMP_ROOT"
  exit "$exit_code"
}
trap cleanup EXIT

psql_cmd() {
  "$PG_BIN/psql" -X -v ON_ERROR_STOP=1 \
    -h "$SOCKET_DIR" -p "$PORT" -U postgres -d postgres "$@"
}

expect_failure() {
  local label="$1"
  local pattern="$2"
  local sql="$3"
  if psql_cmd -q -c "$sql" >"$ERROR_FILE" 2>&1; then
    echo "$label unexpectedly succeeded" >&2
    exit 1
  fi
  if ! rg -q "$pattern" "$ERROR_FILE"; then
    echo "$label failed for an unexpected reason" >&2
    sed -n '1,160p' "$ERROR_FILE" >&2
    exit 1
  fi
}

expect_migration_failure() {
  local label="$1"
  local pattern="$2"
  if psql_cmd -q -f "$MIGRATION" >"$ERROR_FILE" 2>&1; then
    echo "$label unexpectedly succeeded" >&2
    exit 1
  fi
  if ! rg -q "$pattern" "$ERROR_FILE"; then
    echo "$label failed for an unexpected reason" >&2
    sed -n '1,180p' "$ERROR_FILE" >&2
    exit 1
  fi
}

"$PG_BIN/initdb" \
  -D "$DATA_DIR" \
  --auth-local=trust \
  --auth-host=trust \
  --encoding=UTF8 \
  --username=postgres \
  --no-locale >/dev/null
"$PG_BIN/pg_ctl" \
  -D "$DATA_DIR" \
  -l "$LOG_FILE" \
  -o "-F -p $PORT -k $SOCKET_DIR -c listen_addresses=" \
  -w start >/dev/null

psql_cmd -q <<'SQL'
CREATE ROLE anon NOLOGIN;
CREATE ROLE authenticated NOLOGIN;
CREATE ROLE service_role NOLOGIN;
CREATE ROLE fixture_rogue NOLOGIN;
CREATE ROLE fixture_delegate NOLOGIN;
CREATE SCHEMA arena;

CREATE TABLE arena.sources (
  registry_slug text NOT NULL,
  filter_source text,
  season_id text NOT NULL,
  is_serving boolean NOT NULL DEFAULT true,
  PRIMARY KEY (registry_slug, season_id)
);

CREATE FUNCTION arena.fixture_authority_pause()
RETURNS void
LANGUAGE plpgsql
STABLE
SET search_path = pg_catalog, pg_temp
AS $$
BEGIN
  IF pg_catalog.current_setting('fixture.pause_authority', true) = 'on' THEN
    PERFORM pg_catalog.pg_sleep(2);
  END IF;
END;
$$;

CREATE FUNCTION public.arena_freshness_expected_sources()
RETURNS TABLE (
  registry_slug text,
  filter_source text,
  exchange_name text,
  season_id text
)
LANGUAGE plpgsql
STABLE
SET search_path = pg_catalog, pg_temp
AS $$
BEGIN
  PERFORM arena.fixture_authority_pause();
  RETURN QUERY
  SELECT
    source_row.registry_slug,
    source_row.filter_source,
    'Fixture'::text,
    source_row.season_id
  FROM arena.sources AS source_row
  WHERE source_row.is_serving;
END;
$$;

CREATE TABLE public.leaderboard_ranks (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  season_id text NOT NULL,
  source text NOT NULL,
  source_trader_id text NOT NULL,
  rank integer,
  arena_score numeric,
  pnl numeric,
  win_rate numeric,
  max_drawdown numeric,
  score_completeness text,
  metrics_estimated boolean,
  is_outlier boolean,
  computed_at timestamptz,
  rank_publication_id uuid
);

CREATE FUNCTION arena.leaderboard_rank_row_is_public_eligible(
  p_rank public.leaderboard_ranks,
  p_observed_at timestamptz
)
RETURNS boolean
LANGUAGE sql
IMMUTABLE
PARALLEL SAFE
SET search_path = pg_catalog, pg_temp
AS $$
  SELECT p_rank.id IS NOT NULL AND p_observed_at IS NOT NULL
$$;

CREATE TABLE public.leaderboard_source_freshness (
  season_id text NOT NULL,
  source text NOT NULL,
  source_as_of timestamptz NOT NULL,
  recorded_at timestamptz NOT NULL,
  score_cohort_id uuid,
  rank_mutation_seq bigint,
  published_rank_count integer,
  published_identity_sha256 text,
  PRIMARY KEY (season_id, source)
);

CREATE TABLE arena.leaderboard_rank_mutation_fences (
  season_id text NOT NULL,
  source text NOT NULL,
  mutation_seq bigint NOT NULL,
  PRIMARY KEY (season_id, source)
);

CREATE TABLE arena.leaderboard_rank_publications (
  id uuid PRIMARY KEY,
  season_id text NOT NULL,
  published_at timestamptz NOT NULL,
  source_count integer NOT NULL,
  proofs jsonb NOT NULL
);

CREATE FUNCTION public.arena_leaderboard_publication_proofs(
  p_season_id text,
  p_sources text[]
)
RETURNS TABLE (
  season_id text,
  source text,
  source_as_of timestamptz,
  recorded_at timestamptz,
  score_cohort_id uuid,
  rank_mutation_seq bigint,
  current_mutation_seq bigint,
  published_rank_count integer,
  published_identity_sha256 text,
  is_sealed boolean
)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, pg_temp
AS $$
BEGIN
  RETURN;
END;
$$;
ALTER FUNCTION public.arena_leaderboard_publication_proofs(text, text[])
  OWNER TO postgres;
REVOKE ALL
  ON FUNCTION public.arena_leaderboard_publication_proofs(text, text[])
  FROM PUBLIC, anon, authenticated, service_role;
GRANT EXECUTE
  ON FUNCTION public.arena_leaderboard_publication_proofs(text, text[])
  TO service_role;
GRANT EXECUTE
  ON FUNCTION public.arena_leaderboard_publication_proofs(text, text[])
  TO fixture_rogue WITH GRANT OPTION;
SET ROLE fixture_rogue;
GRANT EXECUTE
  ON FUNCTION public.arena_leaderboard_publication_proofs(text, text[])
  TO fixture_delegate;
RESET ROLE;

INSERT INTO arena.sources (
  registry_slug,
  filter_source,
  season_id
) VALUES
  ('alpha', 'alpha', '90D'),
  ('alpha_alias', 'alpha', '90D'),
  ('beta', 'beta', '90D'),
  ('race_alpha', 'race_alpha', '30D'),
  ('race_beta', 'race_beta', '30D');

INSERT INTO public.leaderboard_source_freshness (
  season_id,
  source,
  source_as_of,
