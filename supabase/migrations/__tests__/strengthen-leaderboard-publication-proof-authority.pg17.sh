  '2026-07-25 00:00:00+00',
  '2026-07-25 00:01:00+00',
  NULL,
  NULL,
  NULL,
  NULL
);
SQL

# A same-name overload must abort the forward migration without replacing the
# exact function. Remove it, then prove historical/delegated ACL convergence.
psql_cmd -q <<'SQL'
CREATE FUNCTION public.arena_leaderboard_publication_proofs(text)
RETURNS boolean
LANGUAGE sql
AS $$ SELECT false $$;
SQL
expect_migration_failure \
  "same-name proof overload" \
  "unsupported overload"
psql_cmd -q -c \
  'DROP FUNCTION public.arena_leaderboard_publication_proofs(text)'

psql_cmd -q -f "$MIGRATION"
psql_cmd -q -f "$MIGRATION"

psql_cmd -q <<'SQL'
DO $catalog_contract$
DECLARE
  v_function oid :=
    'public.arena_leaderboard_publication_proofs(text,text[])'
      ::pg_catalog.regprocedure;
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_catalog.pg_proc AS function_row
    WHERE function_row.oid = v_function
      AND function_row.proowner = 'postgres'::pg_catalog.regrole
      AND function_row.prosecdef
      AND function_row.provolatile = 's'
      AND function_row.proconfig =
        ARRAY['search_path=pg_catalog, pg_temp']::text[]
  ) OR NOT pg_catalog.has_function_privilege(
    'service_role', v_function, 'EXECUTE'
  ) OR pg_catalog.has_function_privilege(
    'anon', v_function, 'EXECUTE'
  ) OR pg_catalog.has_function_privilege(
    'authenticated', v_function, 'EXECUTE'
  ) OR pg_catalog.has_function_privilege(
    'fixture_rogue', v_function, 'EXECUTE'
  ) OR pg_catalog.has_function_privilege(
    'fixture_delegate', v_function, 'EXECUTE'
  ) OR EXISTS (
    SELECT 1
    FROM pg_catalog.pg_proc AS function_row
    CROSS JOIN LATERAL pg_catalog.aclexplode(
      COALESCE(
        function_row.proacl,
        pg_catalog.acldefault('f', function_row.proowner)
      )
    ) AS expanded
    WHERE function_row.oid = v_function
      AND expanded.privilege_type = 'EXECUTE'
      AND expanded.grantee <> function_row.proowner
      AND expanded.grantee <> 'service_role'::pg_catalog.regrole
  ) THEN
    RAISE EXCEPTION 'proof callable catalog or ACL did not converge';
  END IF;
END
$catalog_contract$;

-- A complete request returns every distinct authority source. A row with an
-- unsealed freshness marker and a source with no marker both remain visible
-- and explicitly false rather than disappearing.
DO $complete_authority$
DECLARE
  v_rows integer;
  v_unsealed boolean;
  v_missing boolean;
BEGIN
  SELECT
    pg_catalog.count(*),
    pg_catalog.bool_and(NOT proof.is_sealed),
    pg_catalog.bool_and(
      CASE proof.source
        WHEN 'alpha' THEN proof.source_as_of IS NOT NULL
        WHEN 'beta' THEN proof.source_as_of IS NULL
        ELSE false
      END
    )
  INTO STRICT v_rows, v_unsealed, v_missing
  FROM public.arena_leaderboard_publication_proofs(
    '90D',
    ARRAY['beta', 'alpha']
  ) AS proof;

  IF v_rows <> 2 OR NOT v_unsealed OR NOT v_missing THEN
    RAISE EXCEPTION
      'complete authority did not return missing/unsealed false rows';
  END IF;
END
$complete_authority$;
SQL

expect_failure \
  "authority subset" \
  "exactly match the season authority" \
  "SELECT * FROM public.arena_leaderboard_publication_proofs('90D', ARRAY['alpha'])"
expect_failure \
  "authority superset" \
  "exactly match the season authority" \
  "SELECT * FROM public.arena_leaderboard_publication_proofs('90D', ARRAY['alpha','beta','gamma'])"
expect_failure \
  "duplicated request source" \
  "invalid, duplicated, or exceed" \
  "SELECT * FROM public.arena_leaderboard_publication_proofs('90D', ARRAY['alpha','alpha'])"
expect_failure \
  "129-character request source" \
  "invalid, duplicated, or exceed" \
  "SELECT * FROM public.arena_leaderboard_publication_proofs('90D', ARRAY[repeat('a',129),'beta'])"
expect_failure \
  "empty request array" \
  "invalid, duplicated, or exceed" \
  "SELECT * FROM public.arena_leaderboard_publication_proofs('90D', ARRAY[]::text[])"
expect_failure \
  "empty season authority" \
  "authority is empty" \
  "SELECT * FROM public.arena_leaderboard_publication_proofs('7D', ARRAY['alpha'])"

# A receipt must stop sealing immediately when the registry authority shrinks.
# Per-current-source membership alone is insufficient because an old receipt
# can still contain a now-retired extra source under the same cohort.
psql_cmd -q <<'SQL'
