          %s,
          'arena_score',
          'desc',
          NULL,
          NULL,
          NULL
        )
      $query$,
      v_offset
    )
    INTO STRICT v_plan;

    IF v_plan #>> '{0,Plan,Node Type}' IS DISTINCT FROM 'Result'
       OR (v_plan #>> '{0,Plan,Actual Rows}')::integer <> 1 THEN
      RAISE EXCEPTION 'composite EXPLAIN did not produce exactly one bounded result';
    END IF;
    v_execution_ms := (v_plan #>> '{0,Execution Time}')::numeric;
    IF v_execution_ms > 5000 THEN
      RAISE EXCEPTION
        'scaled composite page exceeded 5s fixture budget: offset=%, execution_ms=%',
        v_offset,
        v_execution_ms;
    END IF;
  END LOOP;
END
$plans$;

DO $acl$
BEGIN
  IF pg_catalog.has_function_privilege(
       'anon',
       'public.arena_read_composite_rankings_v1(uuid,uuid,uuid,text[],text[],text[],text[],integer,integer,text,text,numeric,bigint,text)',
