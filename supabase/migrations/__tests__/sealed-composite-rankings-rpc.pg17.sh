DECLARE
  v_definition text;
  v_page_keys_at integer;
  v_wide_page_at integer;
BEGIN
  v_definition := pg_catalog.pg_get_functiondef(
    'public.arena_read_composite_rankings_v1(uuid,uuid,uuid,text[],text[],text[],text[],integer,integer,text,text,numeric,bigint,text)'::pg_catalog.regprocedure
  );
  v_page_keys_at := pg_catalog.strpos(
    v_definition,
    'page_keys AS MATERIALIZED'
  );
  v_wide_page_at := pg_catalog.strpos(
    v_definition,
    E'\n    page AS MATERIALIZED'
  );
  IF pg_catalog.strpos(v_definition, 'WITH season_scores AS MATERIALIZED') = 0
     OR v_page_keys_at = 0
     OR v_wide_page_at <= v_page_keys_at
     OR pg_catalog.strpos(v_definition, 'canonical_season_rows') <> 0
     OR pg_catalog.strpos(v_definition, 'identity_copy = 1') <> 0 THEN
    RAISE EXCEPTION 'composite execution structure regressed to wide or silent-dedup phases';
  END IF;
END
$structure$;

DO $plans$
DECLARE
  v_offset integer;
  v_plan jsonb;
  v_execution_ms numeric;
BEGIN
  FOREACH v_offset IN ARRAY ARRAY[0, 1000]
  LOOP
    EXECUTE pg_catalog.format(
      $query$
        EXPLAIN (ANALYZE, BUFFERS, TIMING OFF, FORMAT JSON)
        SELECT public.arena_read_composite_rankings_v1(
          '77777777-7777-4777-8777-777777777777',
          '30303030-3030-4030-8030-303030303030',
