RECEIPT_BOUNDARY="$(
  psql_cmd -Atqc "
    SELECT
      (table_row.relowner = 'postgres'::pg_catalog.regrole) || '|' ||
      table_row.relrowsecurity || '|' ||
      (NOT table_row.relforcerowsecurity) || '|' ||
      (NOT pg_catalog.has_table_privilege(
        'service_role', table_row.oid, 'SELECT'
      )) || '|' ||
      (NOT pg_catalog.has_table_privilege(
        'service_role', table_row.oid, 'INSERT'
