DO $delayed_replay$
DECLARE
  v_a uuid := 'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa'::uuid;
  v_b uuid := 'bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb'::uuid;
  v_empty_request jsonb := '[
    {"source":"source_a","trader_ids":[]},
    {"source":"source_empty","trader_ids":[]}
  ]'::jsonb;
  v_b_request jsonb := '[
    {"source":"source_a","trader_ids":["new-b-a"]},
    {"source":"source_empty","trader_ids":["new-b-empty"]}
  ]'::jsonb;
  v_a_first jsonb;
  v_b_first jsonb;
  v_a_delayed jsonb;
BEGIN
  v_a_first := public.cleanup_leaderboard_rank_publication(
    '30D', v_a, v_empty_request
  );

  INSERT INTO public.leaderboard_ranks (
    season_id, source, source_trader_id, rank_publication_id
  ) VALUES
    ('30D', 'source_a', 'new-b-a', v_b),
    ('30D', 'source_empty', 'new-b-empty', v_b);

  v_b_first := public.cleanup_leaderboard_rank_publication(
    '30D', v_b, v_b_request
  );
  v_a_delayed := public.cleanup_leaderboard_rank_publication(
    '30D', v_a, v_empty_request
  );

  IF (v_a_first->>'deleted_count')::bigint IS DISTINCT FROM 2
     OR v_a_delayed IS DISTINCT FROM v_a_first THEN
    RAISE EXCEPTION
      'delayed cleanup replay did not return its frozen receipt: first=%, replay=%',
      v_a_first, v_a_delayed;
  END IF;
  IF (v_b_first->>'deleted_count')::bigint IS DISTINCT FROM 0
     OR (v_b_first->>'kept_count')::bigint IS DISTINCT FROM 2 THEN
    RAISE EXCEPTION 'new cohort cleanup receipt drifted: %', v_b_first;
  END IF;
  IF (
    SELECT pg_catalog.count(*)
    FROM public.leaderboard_ranks AS ranks
    WHERE ranks.season_id = '30D'
      AND ranks.rank_publication_id = v_b
      AND (ranks.source, ranks.source_trader_id) IN (
        ('source_a', 'new-b-a'),
        ('source_empty', 'new-b-empty')
      )
  ) <> 2 THEN
    RAISE EXCEPTION 'delayed cleanup replay deleted the newer cohort';
  END IF;

  BEGIN
    PERFORM public.cleanup_leaderboard_rank_publication(
      '30D', v_a, v_b_request
    );
    RAISE EXCEPTION 'same cleanup cohort accepted a different payload';
  EXCEPTION
    WHEN unique_violation THEN
      IF SQLERRM NOT LIKE
           '%score cohort id was reused with different cleanup input%' THEN
        RAISE;
      END IF;
  END;
END
$delayed_replay$;
