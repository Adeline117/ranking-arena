# Prove the SHARE ROW EXCLUSIVE cleanup lock conflicts with ordinary parent
# RowExclusiveLock DML. A same-cohort concurrent duplicate must in turn wait on
# the advisory lock, then return the first cleanup's frozen deleted_count.
psql_cmd -q -c "
  UPDATE public.leaderboard_ranks
  SET rank_publication_id =
    '33333333-3333-4333-8333-333333333333'::uuid
  WHERE season_id = '90D'
    AND source = 'source_a'
    AND source_trader_id = 'keep-a';

  INSERT INTO public.leaderboard_ranks (
    season_id, source, source_trader_id, rank_publication_id
  ) VALUES (
    '90D',
    'source_empty',
    'lock-stale',
    '22222222-2222-4222-8222-222222222222'::uuid
  );
"

HOLDER_OUTPUT="$TMP_ROOT/dml-holder.log"
PGAPPNAME=cleanup_rank_dml_holder \
  psql_cmd -q >"$HOLDER_OUTPUT" 2>&1 <<'SQL' &
BEGIN;
UPDATE public.leaderboard_ranks
SET rank = rank
WHERE season_id = '90D'
  AND source = 'non_authority'
  AND source_trader_id = 'must-survive';
SELECT pg_catalog.pg_sleep(3);
COMMIT;
SQL
HOLDER_PID=$!
HOLDER_SLEEPING=false

for _attempt in {1..100}; do
  HOLDER_WAIT="$(
    psql_cmd -Atqc "
      SELECT COALESCE(activity.wait_event, '')
      FROM pg_catalog.pg_stat_activity AS activity
      WHERE activity.application_name = 'cleanup_rank_dml_holder'
      LIMIT 1;
    "
  )"
  if [[ "$HOLDER_WAIT" == "PgSleep" ]]; then
    HOLDER_SLEEPING=true
    break
  fi
  if ! kill -0 "$HOLDER_PID" 2>/dev/null; then
    break
  fi
  sleep 0.05
done

if [[ "$HOLDER_SLEEPING" != "true" ]]; then
  wait "$HOLDER_PID" || true
  echo "rank DML holder never acquired its parent RowExclusiveLock" >&2
  exit 1
fi

LOCK_CLEANUP_OUTPUT="$TMP_ROOT/lock-cleanup-result.txt"
PGAPPNAME=cleanup_rank_waiter \
  psql_cmd -Atq -c "
    SELECT
      (result->>'deleted_count') || '|' || (result->>'kept_count')
    FROM (
      SELECT public.cleanup_leaderboard_rank_publication(
        '90D',
    '33333333-3333-4333-8333-333333333333'::uuid,
        '[
          {\"source\":\"source_a\",\"trader_ids\":[\"keep-a\"]},
          {\"source\":\"source_empty\",\"trader_ids\":[]}
        ]'::jsonb
      ) AS result
    ) AS cleanup;
  " >"$LOCK_CLEANUP_OUTPUT" &
LOCK_CLEANUP_PID=$!
LOCK_WAIT_OBSERVED=false

for _attempt in {1..100}; do
  CLEANUP_WAIT="$(
    psql_cmd -Atqc "
      SELECT COALESCE(activity.wait_event_type, '') || '|' ||
             COALESCE(activity.wait_event, '')
      FROM pg_catalog.pg_stat_activity AS activity
      WHERE activity.application_name = 'cleanup_rank_waiter'
      LIMIT 1;
    "
  )"
  if [[ "$CLEANUP_WAIT" == "Lock|relation" ]]; then
    LOCK_WAIT_OBSERVED=true
    break
  fi
  if ! kill -0 "$LOCK_CLEANUP_PID" 2>/dev/null; then
    break
  fi
  sleep 0.05
done

if [[ "$LOCK_WAIT_OBSERVED" != "true" ]]; then
  wait "$HOLDER_PID" || true
  wait "$LOCK_CLEANUP_PID" || true
  echo "cleanup did not wait on parent rank DML: $CLEANUP_WAIT" >&2
  exit 1
fi

DUPLICATE_CLEANUP_OUTPUT="$TMP_ROOT/duplicate-cleanup-result.txt"
PGAPPNAME=cleanup_rank_duplicate \
  psql_cmd -Atq -c "
    SELECT
      (result->>'deleted_count') || '|' || (result->>'kept_count')
    FROM (
      SELECT public.cleanup_leaderboard_rank_publication(
        '90D',
        '33333333-3333-4333-8333-333333333333'::uuid,
        '[
          {\"source\":\"source_a\",\"trader_ids\":[\"keep-a\"]},
          {\"source\":\"source_empty\",\"trader_ids\":[]}
        ]'::jsonb
      ) AS result
    ) AS cleanup;
  " >"$DUPLICATE_CLEANUP_OUTPUT" &
DUPLICATE_CLEANUP_PID=$!
ADVISORY_WAIT_OBSERVED=false

for _attempt in {1..100}; do
  DUPLICATE_WAIT="$(
    psql_cmd -Atqc "
      SELECT COALESCE(activity.wait_event_type, '') || '|' ||
             COALESCE(activity.wait_event, '')
      FROM pg_catalog.pg_stat_activity AS activity
      WHERE activity.application_name = 'cleanup_rank_duplicate'
      LIMIT 1;
    "
  )"
  if [[ "$DUPLICATE_WAIT" == "Lock|advisory" ]]; then
    ADVISORY_WAIT_OBSERVED=true
    break
  fi
  if ! kill -0 "$DUPLICATE_CLEANUP_PID" 2>/dev/null; then
    break
  fi
  sleep 0.05
done

if [[ "$ADVISORY_WAIT_OBSERVED" != "true" ]]; then
  wait "$HOLDER_PID" || true
  wait "$LOCK_CLEANUP_PID" || true
  wait "$DUPLICATE_CLEANUP_PID" || true
  echo "concurrent duplicate cleanup did not wait on its cohort receipt: $DUPLICATE_WAIT" >&2
  exit 1
fi

BLOCKED_STALE_COUNT="$(
  psql_cmd -Atqc "
    SELECT pg_catalog.count(*)
    FROM public.leaderboard_ranks
    WHERE season_id = '90D'
      AND source = 'source_empty'
      AND source_trader_id = 'lock-stale';
  "
)"
if [[ "$BLOCKED_STALE_COUNT" != "1" ]]; then
  echo "cleanup partially deleted rows before acquiring its rank lock" >&2
  exit 1
fi

wait "$HOLDER_PID"
wait "$LOCK_CLEANUP_PID"
wait "$DUPLICATE_CLEANUP_PID"

LOCK_CLEANUP_RESULT="$(tr -d '\r\n' <"$LOCK_CLEANUP_OUTPUT")"
if [[ "$LOCK_CLEANUP_RESULT" != "1|1" ]]; then
  echo "cleanup did not resume atomically after rank DML: $LOCK_CLEANUP_RESULT" >&2
  exit 1
fi

DUPLICATE_CLEANUP_RESULT="$(tr -d '\r\n' <"$DUPLICATE_CLEANUP_OUTPUT")"
if [[ "$DUPLICATE_CLEANUP_RESULT" != "1|1" ]]; then
  echo "concurrent duplicate cleanup did not return the frozen receipt: $DUPLICATE_CLEANUP_RESULT" >&2
  exit 1
fi

# Receipt insertion and rank deletion are one transaction. An outer rollback
# must restore the prior cohort and leave no replay receipt behind.
psql_cmd -q <<'SQL'
BEGIN;
UPDATE public.leaderboard_ranks
SET rank_publication_id =
  'dddddddd-dddd-4ddd-8ddd-dddddddddddd'::uuid
WHERE season_id = '90D'
  AND source = 'source_a'
  AND source_trader_id = 'keep-a';
INSERT INTO public.leaderboard_ranks (
  season_id, source, source_trader_id, rank_publication_id
) VALUES (
  '90D',
  'source_empty',
  'transaction-rollback-stale',
  '22222222-2222-4222-8222-222222222222'::uuid
);
DO $inside_rollback$
DECLARE
  v_result jsonb;
BEGIN
  v_result := public.cleanup_leaderboard_rank_publication(
    '90D',
    'dddddddd-dddd-4ddd-8ddd-dddddddddddd'::uuid,
    '[
      {"source":"source_a","trader_ids":["keep-a"]},
      {"source":"source_empty","trader_ids":[]}
    ]'::jsonb
  );
  IF (v_result->>'deleted_count')::bigint IS DISTINCT FROM 1
     OR NOT EXISTS (
       SELECT 1
       FROM arena.leaderboard_rank_cleanup_receipts AS receipt
       WHERE receipt.score_cohort_id =
         'dddddddd-dddd-4ddd-8ddd-dddddddddddd'::uuid
     ) THEN
    RAISE EXCEPTION 'cleanup receipt was not atomic with its DELETE';
  END IF;
END
$inside_rollback$;
ROLLBACK;

DO $after_rollback$
BEGIN
  IF EXISTS (
    SELECT 1
    FROM arena.leaderboard_rank_cleanup_receipts AS receipt
    WHERE receipt.score_cohort_id =
      'dddddddd-dddd-4ddd-8ddd-dddddddddddd'::uuid
  ) OR EXISTS (
    SELECT 1
    FROM public.leaderboard_ranks AS ranks
    WHERE ranks.source_trader_id = 'transaction-rollback-stale'
  ) OR NOT EXISTS (
    SELECT 1
    FROM public.leaderboard_ranks AS ranks
    WHERE ranks.season_id = '90D'
      AND ranks.source = 'source_a'
      AND ranks.source_trader_id = 'keep-a'
      AND ranks.rank_publication_id =
        '33333333-3333-4333-8333-333333333333'::uuid
  ) THEN
    RAISE EXCEPTION 'cleanup transaction rollback left partial state';
  END IF;
END
$after_rollback$;
SQL

