RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, pg_temp
SET lock_timeout = '10s'
AS $function$
BEGIN
  RETURN pg_catalog.jsonb_build_object('status', 'claimed');
END;
$function$;

CREATE FUNCTION public.stage_leaderboard_rank_generation_batch_v1(
  p_season_id text,
  p_generation_seq bigint,
  p_score_cohort_id uuid,
  p_batch_index integer,
  p_score_input_manifest_id uuid,
  p_score_input_manifest_digest text,
  p_batch_sha256_plan text[],
  p_rows jsonb
)
RETURNS jsonb
LANGUAGE plpgsql
VOLATILE
CALLED ON NULL INPUT
PARALLEL UNSAFE
SECURITY DEFINER
SET search_path = pg_catalog, pg_temp
SET "TimeZone" = 'UTC'
SET lock_timeout = '10s'
AS $function$
BEGIN
  INSERT INTO arena.leaderboard_rank_stage_fixture (
    season_id,
    generation_seq,
    batch_index
  ) VALUES (
    p_season_id,
    p_generation_seq,
    p_batch_index
  )
  ON CONFLICT (season_id, generation_seq, batch_index) DO NOTHING;
  RETURN pg_catalog.jsonb_build_object('status', 'staged');
END;
$function$;

CREATE FUNCTION public.finalize_leaderboard_rank_generation_v1(
  p_season_id text,
  p_generation_seq bigint,
  p_score_cohort_id uuid,
  p_score_input_manifest_id uuid,
  p_score_input_manifest_digest text,
  p_source_publications jsonb
)
RETURNS jsonb
LANGUAGE plpgsql
VOLATILE
CALLED ON NULL INPUT
PARALLEL UNSAFE
SECURITY DEFINER
SET search_path = pg_catalog, pg_temp
SET "TimeZone" = 'UTC'
SET lock_timeout = '10s'
AS $function$
BEGIN
  INSERT INTO public.leaderboard_ranks (
    season_id,
    source,
    source_trader_id,
    marker
  ) VALUES (
    p_season_id,
    'atomic_fixture',
    p_score_cohort_id::text,
    p_generation_seq::integer
  )
  ON CONFLICT (season_id, source, source_trader_id) DO UPDATE
  SET marker = EXCLUDED.marker;

  DELETE FROM public.leaderboard_ranks AS rank_row
  WHERE rank_row.season_id = p_season_id
    AND rank_row.source = 'legacy_stale';

  RETURN pg_catalog.jsonb_build_object('status', 'finalized');
END;
$function$;

ALTER FUNCTION public.prepare_leaderboard_score_input_manifest_v1(
  text, text, text, text, jsonb, text, jsonb, text, jsonb, jsonb, timestamptz
) OWNER TO postgres;
ALTER FUNCTION public.plan_leaderboard_rank_generation_batch_v1(
  text, uuid, timestamptz, jsonb
) OWNER TO postgres;
ALTER FUNCTION public.plan_leaderboard_rank_generation_write_set_v1(
  text, uuid, text, timestamptz, integer, text[]
