REVOKE ALL ON ALL FUNCTIONS IN SCHEMA public
  FROM PUBLIC, anon, authenticated, service_role;
GRANT EXECUTE ON FUNCTION public.prepare_leaderboard_score_input_manifest_v1(
  text, text, text, text, jsonb, text, jsonb, text, jsonb, jsonb, timestamptz
) TO service_role;
GRANT EXECUTE ON FUNCTION public.plan_leaderboard_rank_generation_batch_v1(
  text, uuid, timestamptz, jsonb
) TO service_role;
GRANT EXECUTE ON FUNCTION public.plan_leaderboard_rank_generation_write_set_v1(
  text, uuid, text, timestamptz, integer, text[]
) TO service_role;
GRANT EXECUTE ON FUNCTION public.claim_leaderboard_rank_generation(
  text, uuid, text, integer, integer, timestamptz, integer
) TO service_role;
GRANT EXECUTE ON FUNCTION public.stage_leaderboard_rank_generation_batch_v1(
  text, bigint, uuid, integer, uuid, text, text[], jsonb
) TO service_role;
GRANT EXECUTE ON FUNCTION public.finalize_leaderboard_rank_generation_v1(
  text, bigint, uuid, uuid, text, jsonb
) TO service_role;

GRANT SELECT ON TABLE public.leaderboard_ranks
  TO anon, authenticated, service_role;
GRANT ALL PRIVILEGES ON TABLE public.leaderboard_ranks TO service_role;
GRANT INSERT, UPDATE, DELETE, TRUNCATE, REFERENCES, TRIGGER, MAINTAIN
  ON TABLE public.leaderboard_ranks TO PUBLIC, anon, authenticated;
