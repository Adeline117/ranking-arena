#!/usr/bin/env bash

# PostgreSQL 17 behavioral proof for the postdeploy leaderboard-rank DML
# closure. The fixture begins with table-, partition-, PUBLIC-, and column-level
# mutation grants, then proves only postgres-owned SECURITY DEFINER publication
# RPCs can still change live ranks.

set -Eeuo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)"
MIGRATION="$ROOT_DIR/supabase/migrations/20260729152000_close_leaderboard_rank_direct_writes.sql"
PG_BIN="${PG17_BIN:-/opt/homebrew/opt/postgresql@17/bin}"

for executable in initdb pg_ctl psql; do
  if [[ ! -x "$PG_BIN/$executable" ]]; then
    echo "PostgreSQL 17 executable not found: $PG_BIN/$executable" >&2
    exit 1
  fi
done
if [[ "$("$PG_BIN/psql" --version)" != psql\ \(PostgreSQL\)\ 17.* ]]; then
  echo "This integration proof requires PostgreSQL 17" >&2
  exit 1
fi

TMP_ROOT="$(mktemp -d /tmp/close-leaderboard-rank-dml-pg17.XXXXXX)"
DATA_DIR="$TMP_ROOT/data"
SOCKET_DIR="$TMP_ROOT/socket"
LOG_FILE="$TMP_ROOT/postgres.log"
ERROR_FILE="$TMP_ROOT/expected-error.log"
PORT="${PGPORT_OVERRIDE:-$((52000 + ($$ % 9000)))}"
mkdir -p "$SOCKET_DIR"

cleanup() {
  local exit_code=$?
  if [[ -s "$DATA_DIR/postmaster.pid" ]]; then
    "$PG_BIN/pg_ctl" -D "$DATA_DIR" -m immediate -w stop >/dev/null 2>&1 || true
  fi
  if ((exit_code != 0)); then
    [[ -f "$ERROR_FILE" ]] && sed -n '1,180p' "$ERROR_FILE" >&2 || true
    [[ -f "$LOG_FILE" ]] && tail -240 "$LOG_FILE" >&2 || true
  fi
  rm -rf "$TMP_ROOT"
  exit "$exit_code"
}
trap cleanup EXIT

psql_cmd() {
  "$PG_BIN/psql" -X -v ON_ERROR_STOP=1 -v VERBOSITY=verbose \
    -h "$SOCKET_DIR" -p "$PORT" -U postgres -d postgres "$@"
}

role_query() {
  local role="$1"
  local sql="$2"
  psql_cmd -qAtc "
    SET ROLE $role;
    $sql
    RESET ROLE;
  "
}

expect_value() {
  local label="$1"
  local expected="$2"
  local role="$3"
  local sql="$4"
  local actual
  actual="$(role_query "$role" "$sql")"
  if [[ "$actual" != "$expected" ]]; then
    echo "$label drifted: expected '$expected', got '$actual'" >&2
    exit 1
  fi
}

expect_failure() {
  local label="$1"
  local role="$2"
  local sql="$3"
  if role_query "$role" "$sql" >"$ERROR_FILE" 2>&1; then
    echo "$label unexpectedly succeeded" >&2
    exit 1
  fi
  if ! grep -Eq 'permission denied|42501' "$ERROR_FILE"; then
    echo "$label failed for an unexpected reason" >&2
    sed -n '1,180p' "$ERROR_FILE" >&2
    exit 1
  fi
}

"$PG_BIN/initdb" \
  -D "$DATA_DIR" \
  --auth-local=trust \
  --auth-host=trust \
  --encoding=UTF8 \
  --username=postgres \
  --no-locale >/dev/null
"$PG_BIN/pg_ctl" \
  -D "$DATA_DIR" \
  -l "$LOG_FILE" \
  -o "-F -p $PORT -k $SOCKET_DIR -c listen_addresses=" \
  -w start >/dev/null

psql_cmd -q <<'SQL'
CREATE ROLE anon NOLOGIN;
CREATE ROLE authenticated NOLOGIN;
CREATE ROLE service_role NOLOGIN;
CREATE SCHEMA arena AUTHORIZATION postgres;
GRANT USAGE ON SCHEMA public TO anon, authenticated, service_role;

CREATE TABLE public.leaderboard_ranks (
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  season_id text NOT NULL,
  source text NOT NULL,
  source_trader_id text NOT NULL,
  marker integer NOT NULL DEFAULT 0,
  PRIMARY KEY (season_id, id),
  UNIQUE (season_id, source, source_trader_id)
) PARTITION BY LIST (season_id);
CREATE TABLE public.leaderboard_ranks_7d
  PARTITION OF public.leaderboard_ranks FOR VALUES IN ('7D');
CREATE TABLE public.leaderboard_ranks_30d
  PARTITION OF public.leaderboard_ranks FOR VALUES IN ('30D');
CREATE TABLE public.leaderboard_ranks_90d
  PARTITION OF public.leaderboard_ranks FOR VALUES IN ('90D');
ALTER TABLE public.leaderboard_ranks OWNER TO postgres;
ALTER TABLE public.leaderboard_ranks_7d OWNER TO postgres;
ALTER TABLE public.leaderboard_ranks_30d OWNER TO postgres;
ALTER TABLE public.leaderboard_ranks_90d OWNER TO postgres;

CREATE TABLE arena.leaderboard_rank_stage_fixture (
  season_id text NOT NULL,
  generation_seq bigint NOT NULL,
  batch_index integer NOT NULL,
  PRIMARY KEY (season_id, generation_seq, batch_index)
);
ALTER TABLE arena.leaderboard_rank_stage_fixture OWNER TO postgres;
REVOKE ALL ON TABLE arena.leaderboard_rank_stage_fixture FROM PUBLIC;

CREATE FUNCTION public.prepare_leaderboard_score_input_manifest_v1(
  p_period text,
  p_source_bundle_digest text,
  p_score_rows_sha256 text,
  p_physical_boards_sha256 text,
  p_source_evidence jsonb,
  p_enrichment_contract text,
  p_enrichment_evidence jsonb,
  p_eligibility_contract text,
  p_eligibility_evidence jsonb,
  p_inputs jsonb,
  p_valid_until timestamptz
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, pg_temp
AS $function$
BEGIN
  RETURN pg_catalog.jsonb_build_object('status', 'prepared');
END;
$function$;

CREATE FUNCTION public.plan_leaderboard_rank_generation_batch_v1(
  p_season_id text,
  p_score_cohort_id uuid,
  p_computed_at timestamptz,
  p_rows jsonb
)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
PARALLEL SAFE
SECURITY DEFINER
SET search_path = pg_catalog, pg_temp
SET "TimeZone" = 'UTC'
AS $function$
BEGIN
  RETURN pg_catalog.jsonb_build_object('status', 'batch_planned');
END;
$function$;

CREATE FUNCTION public.plan_leaderboard_rank_generation_write_set_v1(
  p_season_id text,
  p_score_cohort_id uuid,
  p_score_input_manifest_digest text,
  p_computed_at timestamptz,
  p_expected_rank_count integer,
  p_batch_sha256_plan text[]
)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
PARALLEL SAFE
SECURITY DEFINER
SET search_path = pg_catalog, pg_temp
SET "TimeZone" = 'UTC'
AS $function$
BEGIN
  RETURN pg_catalog.jsonb_build_object('status', 'write_set_planned');
END;
$function$;

CREATE FUNCTION public.claim_leaderboard_rank_generation(
  p_season_id text,
  p_score_cohort_id uuid,
  p_write_set_sha256 text,
  p_expected_rank_count integer,
  p_expected_batch_count integer,
  p_computed_at timestamptz,
  p_lease_seconds integer
