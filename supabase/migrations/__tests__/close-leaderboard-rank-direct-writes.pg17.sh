  ON TABLE public.leaderboard_ranks_7d TO PUBLIC, anon, authenticated, service_role;
GRANT INSERT (source_trader_id), UPDATE (marker), REFERENCES (source)
  ON TABLE public.leaderboard_ranks
  TO anon, authenticated, service_role;
GRANT INSERT (source_trader_id), UPDATE (marker), REFERENCES (source)
  ON TABLE public.leaderboard_ranks_7d
  TO PUBLIC, anon, authenticated, service_role;

INSERT INTO public.leaderboard_ranks (
