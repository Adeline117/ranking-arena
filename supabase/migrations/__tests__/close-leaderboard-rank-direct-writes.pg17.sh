# The cutover itself is replay safe and must converge broad legacy ACLs twice.
psql_cmd -q -f "$MIGRATION"
psql_cmd -q -f "$MIGRATION"

psql_cmd -q <<'SQL'
DO $assert_acl$
DECLARE
  v_authority record;
  v_relation regclass;
  v_role name;
  v_privilege text;
BEGIN
  FOREACH v_role IN ARRAY ARRAY[
    'service_role'::name,
    'anon'::name,
    'authenticated'::name
  ]
  LOOP
    FOR v_relation IN
      SELECT partition.relid::regclass
      FROM pg_catalog.pg_partition_tree(
        'public.leaderboard_ranks'::pg_catalog.regclass
      ) AS partition
    LOOP
      FOREACH v_privilege IN ARRAY ARRAY[
        'INSERT', 'UPDATE', 'DELETE', 'TRUNCATE',
        'REFERENCES', 'TRIGGER', 'MAINTAIN'
      ]::text[]
      LOOP
        IF pg_catalog.has_table_privilege(
             v_role,
             v_relation,
             v_privilege
           ) THEN
          RAISE EXCEPTION '% still has % on %',
            v_role,
            v_privilege,
            v_relation;
        END IF;
      END LOOP;
    END LOOP;
  END LOOP;

  IF NOT pg_catalog.has_table_privilege(
       'service_role', 'public.leaderboard_ranks', 'SELECT'
     )
     OR NOT pg_catalog.has_table_privilege(
       'anon', 'public.leaderboard_ranks', 'SELECT'
     )
     OR NOT pg_catalog.has_table_privilege(
       'authenticated', 'public.leaderboard_ranks', 'SELECT'
     )
     OR EXISTS (
       SELECT 1
       FROM pg_catalog.pg_partition_tree(
         'public.leaderboard_ranks'::pg_catalog.regclass
       ) AS partition
       JOIN pg_catalog.pg_attribute AS attribute
         ON attribute.attrelid = partition.relid
       CROSS JOIN LATERAL pg_catalog.aclexplode(attribute.attacl) AS expanded
       WHERE expanded.grantee IN (
         0,
         'service_role'::pg_catalog.regrole,
         'anon'::pg_catalog.regrole,
         'authenticated'::pg_catalog.regrole
       )
         AND expanded.privilege_type IN ('INSERT', 'UPDATE', 'REFERENCES')
     ) THEN
    RAISE EXCEPTION 'rank read/column ACL postcondition failed';
  END IF;

  FOR v_authority IN
    SELECT function_row.oid, function_row.proowner, function_row.prosecdef
    FROM pg_catalog.pg_proc AS function_row
    WHERE function_row.oid = ANY(ARRAY[
      'public.prepare_leaderboard_score_input_manifest_v1(text,text,text,text,jsonb,text,jsonb,text,jsonb,jsonb,timestamptz)'::pg_catalog.regprocedure,
      'public.plan_leaderboard_rank_generation_batch_v1(text,uuid,timestamptz,jsonb)'::pg_catalog.regprocedure,
      'public.plan_leaderboard_rank_generation_write_set_v1(text,uuid,text,timestamptz,integer,text[])'::pg_catalog.regprocedure,
      'public.claim_leaderboard_rank_generation(text,uuid,text,integer,integer,timestamptz,integer)'::pg_catalog.regprocedure,
      'public.stage_leaderboard_rank_generation_batch_v1(text,bigint,uuid,integer,uuid,text,text[],jsonb)'::pg_catalog.regprocedure,
      'public.finalize_leaderboard_rank_generation_v1(text,bigint,uuid,uuid,text,jsonb)'::pg_catalog.regprocedure
    ]::oid[])
  LOOP
    IF v_authority.proowner IS DISTINCT FROM
         'postgres'::pg_catalog.regrole
       OR NOT v_authority.prosecdef
       OR NOT pg_catalog.has_function_privilege(
            'service_role', v_authority.oid, 'EXECUTE'
          )
       OR pg_catalog.has_function_privilege(
            'anon', v_authority.oid, 'EXECUTE'
          )
       OR pg_catalog.has_function_privilege(
            'authenticated', v_authority.oid, 'EXECUTE'
          ) THEN
      RAISE EXCEPTION 'publisher authority ACL drifted for %', v_authority.oid;
    END IF;
  END LOOP;
END
$assert_acl$;
SQL

# Read behavior is preserved for every API role.
expect_value \
  "service rank read" \
  "1" \
  service_role \
  "SELECT pg_catalog.count(*) FROM public.leaderboard_ranks;"
expect_value \
  "anonymous rank read" \
  "1" \
  anon \
  "SELECT pg_catalog.count(*) FROM public.leaderboard_ranks;"
expect_value \
  "authenticated rank read" \
  "1" \
  authenticated \
  "SELECT pg_catalog.count(*) FROM public.leaderboard_ranks;"

# Every direct parent/child write path is closed.
for role in service_role anon authenticated; do
  expect_failure \
    "$role direct insert" \
    "$role" \
    "INSERT INTO public.leaderboard_ranks (season_id, source, source_trader_id) VALUES ('7D', 'direct', '$role');"
  expect_failure \
    "$role direct update" \
    "$role" \
    "UPDATE public.leaderboard_ranks SET marker = 9 WHERE season_id = '7D';"
  expect_failure \
    "$role direct delete" \
    "$role" \
    "DELETE FROM public.leaderboard_ranks WHERE season_id = '7D';"
done
expect_failure \
  "service direct partition insert" \
  service_role \
  "INSERT INTO public.leaderboard_ranks_7d (season_id, source, source_trader_id) VALUES ('7D', 'child', 'service');"

# Browser roles cannot invoke the owner authority either.
expect_failure \
  "anonymous finalizer execution" \
  anon \
  "SELECT public.finalize_leaderboard_rank_generation_v1('7D', 1, '10000000-0000-4000-8000-000000000001', '20000000-0000-4000-8000-000000000001', repeat('a', 64), '[]'::jsonb);"
expect_failure \
  "authenticated stage execution" \
  authenticated \
  "SELECT public.stage_leaderboard_rank_generation_batch_v1('7D', 1, '10000000-0000-4000-8000-000000000001', 0, '20000000-0000-4000-8000-000000000001', repeat('a', 64), ARRAY[repeat('b', 64)], '[]'::jsonb);"

# The complete trusted publisher chain remains executable. Stage and finalizer
# prove owner execution behavior, not just catalog grants.
expect_value \
  "manifest preparation RPC" \
  "prepared" \
  service_role \
  "SELECT public.prepare_leaderboard_score_input_manifest_v1('7D', 'a', 'b', 'c', '{}'::jsonb, 'd', '{}'::jsonb, 'e', '{}'::jsonb, '[]'::jsonb, pg_catalog.clock_timestamp())->>'status';"
expect_value \
  "batch planner RPC" \
  "batch_planned" \
  service_role \
  "SELECT public.plan_leaderboard_rank_generation_batch_v1('7D', '10000000-0000-4000-8000-000000000001', pg_catalog.clock_timestamp(), '[]'::jsonb)->>'status';"
expect_value \
  "write-set planner RPC" \
  "write_set_planned" \
  service_role \
  "SELECT public.plan_leaderboard_rank_generation_write_set_v1('7D', '10000000-0000-4000-8000-000000000001', repeat('a', 64), pg_catalog.clock_timestamp(), 1, ARRAY[repeat('b', 64)])->>'status';"
expect_value \
  "claim RPC" \
  "claimed" \
  service_role \
  "SELECT public.claim_leaderboard_rank_generation('7D', '10000000-0000-4000-8000-000000000001', repeat('a', 64), 1, 1, pg_catalog.clock_timestamp(), 60)->>'status';"
expect_value \
  "stage RPC" \
  "staged" \
  service_role \
  "SELECT public.stage_leaderboard_rank_generation_batch_v1('7D', 1, '10000000-0000-4000-8000-000000000001', 0, '20000000-0000-4000-8000-000000000001', repeat('a', 64), ARRAY[repeat('b', 64)], '[]'::jsonb)->>'status';"
expect_value \
  "finalizer RPC" \
  "finalized" \
  service_role \
  "SELECT public.finalize_leaderboard_rank_generation_v1('7D', 1, '10000000-0000-4000-8000-000000000001', '20000000-0000-4000-8000-000000000001', repeat('a', 64), '[]'::jsonb)->>'status';"
expect_value \
  "finalizer response-loss replay" \
  "finalized" \
  service_role \
  "SELECT public.finalize_leaderboard_rank_generation_v1('7D', 1, '10000000-0000-4000-8000-000000000001', '20000000-0000-4000-8000-000000000001', repeat('a', 64), '[]'::jsonb)->>'status';"
expect_value \
  "atomic finalizer replacement set" \
  "1|1|0" \
  service_role \
  "SELECT pg_catalog.count(*) FILTER (WHERE source = 'atomic_fixture') || '|' || pg_catalog.max(marker) FILTER (WHERE source = 'atomic_fixture') || '|' || pg_catalog.count(*) FILTER (WHERE source = 'legacy_stale') FROM public.leaderboard_ranks;"

# Trusted RPC calls do not reopen direct DML.
expect_failure \
  "service direct write after finalization" \
  service_role \
  "UPDATE public.leaderboard_ranks SET marker = 10 WHERE season_id = '7D';"

echo "close leaderboard rank direct writes PostgreSQL 17 proof passed"
