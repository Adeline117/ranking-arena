#!/usr/bin/env bash

# PostgreSQL 17 behavioral proof for the legacy rank-cleanup EXECUTE boundary.

set -Eeuo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)"
MIGRATION="$ROOT_DIR/supabase/migrations/20260725014500_close_rank_cleanup_public_execute.sql"
PG_BIN="${PG17_BIN:-/opt/homebrew/opt/postgresql@17/bin}"

for executable in initdb pg_ctl psql; do
  if [[ ! -x "$PG_BIN/$executable" ]]; then
    echo "PostgreSQL 17 executable not found: $PG_BIN/$executable" >&2
    exit 1
  fi
done
if [[ "$("$PG_BIN/psql" --version)" != psql\ \(PostgreSQL\)\ 17.* ]]; then
  echo "This integration proof requires PostgreSQL 17" >&2
  exit 1
fi

TMP_ROOT="$(mktemp -d /tmp/rank-cleanup-acl-pg17.XXXXXX)"
DATA_DIR="$TMP_ROOT/data"
SOCKET_DIR="$TMP_ROOT/socket"
LOG_FILE="$TMP_ROOT/postgres.log"
ERROR_FILE="$TMP_ROOT/expected-error.log"
PORT="${PGPORT_OVERRIDE:-$((59000 + ($$ % 5000)))}"
mkdir -p "$SOCKET_DIR"

cleanup() {
  local exit_code=$?
  if [[ -s "$DATA_DIR/postmaster.pid" ]]; then
    "$PG_BIN/pg_ctl" -D "$DATA_DIR" -m immediate -w stop >/dev/null 2>&1 || true
  fi
  if ((exit_code != 0)) && [[ -f "$LOG_FILE" ]]; then
    tail -200 "$LOG_FILE" >&2 || true
  fi
  rm -rf "$TMP_ROOT"
  exit "$exit_code"
}
trap cleanup EXIT

psql_cmd() {
  "$PG_BIN/psql" -X -v ON_ERROR_STOP=1 \
    -h "$SOCKET_DIR" -p "$PORT" -U postgres -d postgres "$@"
}

expect_failure() {
  local label="$1"
  local pattern="$2"
  local sql="$3"
  if psql_cmd -q -c "$sql" >"$ERROR_FILE" 2>&1; then
    echo "$label unexpectedly succeeded" >&2
    exit 1
  fi
  if ! rg -q "$pattern" "$ERROR_FILE"; then
    echo "$label failed for an unexpected reason" >&2
    sed -n '1,160p' "$ERROR_FILE" >&2
    exit 1
  fi
}

expect_migration_failure() {
  local label="$1"
  local pattern="$2"
  if psql_cmd -q -f "$MIGRATION" >"$ERROR_FILE" 2>&1; then
    echo "$label unexpectedly succeeded" >&2
    exit 1
  fi
  if ! rg -q "$pattern" "$ERROR_FILE"; then
    echo "$label failed for an unexpected reason" >&2
    sed -n '1,180p' "$ERROR_FILE" >&2
    exit 1
  fi
}

"$PG_BIN/initdb" \
  -D "$DATA_DIR" \
  --auth-local=trust \
  --auth-host=trust \
  --encoding=UTF8 \
  --username=postgres \
  --no-locale >/dev/null
"$PG_BIN/pg_ctl" \
  -D "$DATA_DIR" \
  -l "$LOG_FILE" \
  -o "-F -p $PORT -k $SOCKET_DIR -c listen_addresses=" \
  -w start >/dev/null

psql_cmd -q <<'SQL'
CREATE ROLE anon NOLOGIN;
CREATE ROLE authenticated NOLOGIN;
CREATE ROLE service_role NOLOGIN;
CREATE ROLE fixture_rogue NOLOGIN;
CREATE ROLE fixture_delegate NOLOGIN;
CREATE ROLE fixture_public_only NOLOGIN;

CREATE TABLE public.leaderboard_ranks (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  season_id text NOT NULL,
  source text NOT NULL,
  source_trader_id text NOT NULL
);

CREATE OR REPLACE FUNCTION public.cleanup_stale_platform_rows(
  p_season_id text,
  p_source text,
  p_keep_trader_ids text[]
)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_deleted integer;
BEGIN
  DELETE FROM leaderboard_ranks
  WHERE season_id = p_season_id
    AND source = p_source
    AND source_trader_id != ALL(p_keep_trader_ids)
  ;
  GET DIAGNOSTICS v_deleted = ROW_COUNT;
  RETURN v_deleted;
END;
$$;

GRANT EXECUTE
  ON FUNCTION public.cleanup_stale_platform_rows(text, text, text[])
  TO fixture_rogue WITH GRANT OPTION;
SET ROLE fixture_rogue;
GRANT EXECUTE
  ON FUNCTION public.cleanup_stale_platform_rows(text, text, text[])
  TO fixture_delegate;
RESET ROLE;

INSERT INTO public.leaderboard_ranks (season_id, source, source_trader_id)
VALUES ('30D', 'alpha', 'a'), ('30D', 'alpha', 'b');
SQL

# Prove the historical default PUBLIC grant really gives anon destructive
# execution. Roll the deletion back so the post-migration service call can use
# the same fixture.
if [[ "$(psql_cmd -qAt <<'SQL'
BEGIN;
SET LOCAL ROLE anon;
SELECT public.cleanup_stale_platform_rows(
  '30D',
  'alpha',
  ARRAY[]::text[]
);
ROLLBACK;
SQL
)" != "2" ]]; then
  echo "historical PUBLIC cleanup exposure was not reproduced" >&2
  exit 1
fi

# A same-name overload must abort without changing the exact callable.
psql_cmd -q <<'SQL'
CREATE FUNCTION public.cleanup_stale_platform_rows(text)
RETURNS integer
LANGUAGE sql
AS $$ SELECT 0 $$;
SQL
expect_migration_failure \
  "same-name cleanup overload" \
  "unsupported overload"
psql_cmd -q -c 'DROP FUNCTION public.cleanup_stale_platform_rows(text)'

psql_cmd -q -f "$MIGRATION"
psql_cmd -q -f "$MIGRATION"

psql_cmd -q <<'SQL'
DO $catalog_contract$
DECLARE
  v_function oid :=
    'public.cleanup_stale_platform_rows(text,text,text[])'
      ::pg_catalog.regprocedure;
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_catalog.pg_proc AS function_row
    WHERE function_row.oid = v_function
      AND function_row.proowner = 'postgres'::pg_catalog.regrole
      AND function_row.prosecdef
      AND function_row.provolatile = 'v'
      AND function_row.proconfig = ARRAY['search_path=public']::text[]
  )
     OR NOT pg_catalog.has_function_privilege(
       'service_role', v_function, 'EXECUTE'
     )
     OR pg_catalog.has_function_privilege('anon', v_function, 'EXECUTE')
     OR pg_catalog.has_function_privilege(
       'authenticated', v_function, 'EXECUTE'
     )
     OR pg_catalog.has_function_privilege(
       'fixture_rogue', v_function, 'EXECUTE'
     )
     OR pg_catalog.has_function_privilege(
       'fixture_delegate', v_function, 'EXECUTE'
     )
     OR pg_catalog.has_function_privilege(
       'fixture_public_only', v_function, 'EXECUTE'
     )
     OR EXISTS (
       SELECT 1
       FROM pg_catalog.pg_proc AS function_row
       CROSS JOIN LATERAL pg_catalog.aclexplode(
         COALESCE(
           function_row.proacl,
           pg_catalog.acldefault('f', function_row.proowner)
         )
       ) AS expanded
       WHERE function_row.oid = v_function
         AND expanded.privilege_type = 'EXECUTE'
         AND expanded.grantee <> function_row.proowner
         AND expanded.grantee <> 'service_role'::pg_catalog.regrole
     )
     OR EXISTS (
       SELECT 1
       FROM pg_catalog.pg_proc AS function_row
       CROSS JOIN LATERAL pg_catalog.aclexplode(
         function_row.proacl
       ) AS expanded
       WHERE function_row.oid = v_function
         AND expanded.grantee = 'service_role'::pg_catalog.regrole
         AND expanded.privilege_type = 'EXECUTE'
         AND expanded.is_grantable
     ) THEN
    RAISE EXCEPTION 'legacy cleanup callable ACL did not converge';
  END IF;
END
$catalog_contract$;
SQL

expect_failure \
  "anonymous cleanup" \
  "permission denied for function cleanup_stale_platform_rows" \
  "SET ROLE anon; SELECT public.cleanup_stale_platform_rows('30D','alpha',ARRAY[]::text[]); RESET ROLE"
expect_failure \
  "authenticated cleanup" \
  "permission denied for function cleanup_stale_platform_rows" \
  "SET ROLE authenticated; SELECT public.cleanup_stale_platform_rows('30D','alpha',ARRAY[]::text[]); RESET ROLE"

if [[ "$(psql_cmd -qAt <<'SQL'
SET ROLE service_role;
SELECT public.cleanup_stale_platform_rows(
  '30D',
  'alpha',
  ARRAY['a']::text[]
);
RESET ROLE;
SQL
)" != "1" ]]; then
  echo "service-only cleanup did not preserve legacy cron behavior" >&2
  exit 1
fi

psql_cmd -qAt -c \
  "SELECT source_trader_id FROM public.leaderboard_ranks ORDER BY source_trader_id" \
  | rg -q '^a$'

echo "legacy rank cleanup ACL PG17 proof passed"
