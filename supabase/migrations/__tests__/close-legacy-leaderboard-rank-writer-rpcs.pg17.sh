SET search_path = pg_catalog, pg_temp
SET lock_timeout = '10s'
AS $function$
BEGIN
  DELETE FROM public.leaderboard_ranks
  WHERE season_id = p_season_id
    AND source = 'legacy_stale';
  RETURN pg_catalog.jsonb_build_object('status', 'cleaned');
END;
$function$;

