-- The sole externally executable rank writer. It invokes the two publication
-- helpers after their application EXECUTE grants have been removed.
CREATE FUNCTION public.finalize_leaderboard_rank_generation_v1(
  p_season_id text,
  p_generation_seq bigint,
  p_score_cohort_id uuid,
  p_score_input_manifest_id uuid,
  p_score_input_manifest_digest text,
  p_source_publications jsonb
)
RETURNS jsonb
LANGUAGE plpgsql
VOLATILE
CALLED ON NULL INPUT
PARALLEL UNSAFE
SECURITY DEFINER
SET search_path = pg_catalog, pg_temp
SET "TimeZone" = 'UTC'
SET lock_timeout = '10s'
AS $function$
BEGIN
  INSERT INTO public.leaderboard_ranks (
    season_id,
    source,
    source_trader_id,
    marker
  ) VALUES (
    p_season_id,
    'canonical',
    p_score_cohort_id::text,
    p_generation_seq::integer
  )
  ON CONFLICT (season_id, source, source_trader_id) DO UPDATE
  SET marker = EXCLUDED.marker;

  PERFORM public.cleanup_leaderboard_rank_publication(
    p_season_id,
    p_score_cohort_id,
    p_source_publications
  );
  PERFORM public.rerank_leaderboard_publication(
    p_season_id,
    p_score_cohort_id
  );
  RETURN pg_catalog.jsonb_build_object('status', 'finalized');
END;
$function$;

