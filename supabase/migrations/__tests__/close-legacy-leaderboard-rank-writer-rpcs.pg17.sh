DO $catalog_assertions$
DECLARE
  v_role name;
  v_signature text;
  v_oid oid;
  v_finalizer oid := pg_catalog.to_regprocedure(
    'public.finalize_leaderboard_rank_generation_v1(text,bigint,uuid,uuid,text,jsonb)'
  );
BEGIN
  FOREACH v_signature IN ARRAY ARRAY[
    'public.rerank_leaderboard(text)',
    'public.cleanup_stale_platform_rows(text,text,text[])',
    'public.rerank_leaderboard_publication(text,uuid)',
    'public.cleanup_leaderboard_rank_publication(text,uuid,jsonb)',
    'arena.write_leaderboard_rank_generation_batch_v1(text,bigint,uuid,integer,uuid,text,text[],arena.leaderboard_rank_batch_row_v1[])'
  ]::text[]
  LOOP
    v_oid := pg_catalog.to_regprocedure(v_signature);
    FOREACH v_role IN ARRAY ARRAY[
      'service_role'::name,
      'anon'::name,
      'authenticated'::name
    ]
    LOOP
      IF pg_catalog.has_function_privilege(v_role, v_oid, 'EXECUTE') THEN
        RAISE EXCEPTION '% can still execute legacy writer %', v_role, v_signature;
      END IF;
    END LOOP;

    IF EXISTS (
      SELECT 1
      FROM pg_catalog.pg_proc AS function_row
      CROSS JOIN LATERAL pg_catalog.aclexplode(
        COALESCE(
          function_row.proacl,
          pg_catalog.acldefault('f', function_row.proowner)
        )
      ) AS expanded
      WHERE function_row.oid = v_oid
        AND expanded.privilege_type = 'EXECUTE'
        AND expanded.grantee <> function_row.proowner
    ) THEN
      RAISE EXCEPTION 'legacy writer is not owner-only: %', v_signature;
    END IF;
  END LOOP;

  IF NOT pg_catalog.has_function_privilege(
       'service_role', v_finalizer, 'EXECUTE'
     )
     OR pg_catalog.has_function_privilege('anon', v_finalizer, 'EXECUTE')
     OR pg_catalog.has_function_privilege(
       'authenticated', v_finalizer, 'EXECUTE'
     ) THEN
    RAISE EXCEPTION 'canonical finalizer boundary drifted';
  END IF;
END
$catalog_assertions$;
SQL

