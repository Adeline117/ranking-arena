-- Four historical SECURITY DEFINER rank writers. Each initially bypasses the
-- service-role table ACL exactly as the production legacy surface does.
CREATE FUNCTION public.rerank_leaderboard(p_season_id text)
RETURNS integer
LANGUAGE plpgsql
VOLATILE
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_count integer;
BEGIN
  UPDATE public.leaderboard_ranks
  SET marker = marker + 1
  WHERE season_id = p_season_id;
  GET DIAGNOSTICS v_count = ROW_COUNT;
  RETURN v_count;
END;
$function$;

CREATE FUNCTION public.cleanup_stale_platform_rows(
  p_season_id text,
  p_source text,
  p_keep_trader_ids text[]
)
RETURNS integer
LANGUAGE plpgsql
VOLATILE
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_count integer;
BEGIN
  DELETE FROM leaderboard_ranks
  WHERE season_id = p_season_id
    AND source = p_source
    AND source_trader_id <> ALL(p_keep_trader_ids);
  GET DIAGNOSTICS v_count = ROW_COUNT;
  RETURN v_count;
END;
$function$;

CREATE FUNCTION public.rerank_leaderboard_publication(
  p_season_id text,
  p_score_cohort_id uuid
)
RETURNS jsonb
LANGUAGE plpgsql
VOLATILE
SECURITY DEFINER
SET search_path = pg_catalog, pg_temp
SET lock_timeout = '10s'
AS $function$
BEGIN
  UPDATE public.leaderboard_ranks
  SET marker = marker + 1
  WHERE season_id = p_season_id;
  RETURN pg_catalog.jsonb_build_object('status', 'reranked');
END;
$function$;

CREATE FUNCTION public.cleanup_leaderboard_rank_publication(
  p_season_id text,
  p_score_cohort_id uuid,
  p_source_publications jsonb
)
RETURNS jsonb
LANGUAGE plpgsql
